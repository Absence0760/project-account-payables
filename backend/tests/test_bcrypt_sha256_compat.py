"""Every password already in the database must still verify.

`app/utils/passwords.py` used to delegate to passlib; it now implements the
`bcrypt_sha256` scheme itself, against the `bcrypt` package directly, because
passlib 1.7.4 (unchanged since 2020) reads `bcrypt.__about__.__version__` and
probes the backend by hashing a >72-byte secret — so it cannot import at all
against bcrypt 4.1+, which froze us on bcrypt 4.0.1 (`docs/decisions.md` §151).

The one thing that could go wrong is the digest: `bcrypt_sha256` is NOT
`bcrypt(sha256(password))`. It is an HMAC-SHA256 keyed off the *encoded* salt
text, base64-encoded (not hex) before bcrypt sees it, in a specific string
format that differs between the scheme's v1 and v2. Get any of that wrong and
every stored credential stops verifying — a silent, total lockout that no unit
test of our own round trip would catch, because our own hash and our own verify
would agree with each other perfectly while disagreeing with the column.

So the hashes below are **fixtures passlib itself produced**, pasted in as
literals. The test never imports passlib (it is no longer a dependency); the
literals are the only remaining record of what it emitted, which is exactly why
they are hard-coded rather than generated. Regenerating them requires a passlib
install and is not something a change to our code should ever need.

Covered: v2 (the current format), v1 (pre-passlib-1.7.3, still read), both the
`2b` and the legacy `2a` bcrypt variants, and the plain `$2b$` bcrypt scheme the
codebase wrote before commit c6a91396 upgraded it.
"""

