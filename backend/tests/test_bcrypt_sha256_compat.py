def test_identify_names_each_scheme():
    assert pwd_context.identify(PASSLIB_V2[0][1]) == "bcrypt_sha256"
    assert pwd_context.identify(PASSLIB_V1[0][1]) == "bcrypt_sha256_v1"
    assert pwd_context.identify(PASSLIB_LEGACY_BCRYPT[0][1]) == "bcrypt"
    assert pwd_context.identify("garbage") is None
    assert pwd_context.identify("") is None


def test_needs_update_flags_exactly_the_schemes_we_no_longer_write():
    """passlib's `deprecated=["bcrypt"]` plus its v1 check, reproduced.

    Nothing consults this yet — re-hashing a legacy credential on its owner's
    next login is an open follow-up — so this is the contract that makes wiring
    it up a small change rather than a re-derivation.
    """
    assert pwd_context.needs_update(pwd_context.hash("Correct-Horse-1234")) is False
    assert pwd_context.needs_update(PASSLIB_V2[0][1]) is False
    assert pwd_context.needs_update(PASSLIB_V1[0][1]) is True
    assert pwd_context.needs_update(PASSLIB_LEGACY_BCRYPT[0][1]) is True
    for scheme in pwd_context.deprecated_schemes:
        assert scheme != pwd_context.scheme
