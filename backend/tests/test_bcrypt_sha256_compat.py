@pytest.mark.parametrize(
    "hashed",
    [
        "",
        "not-a-hash",
        "$bcrypt-sha256$",
        "$bcrypt-sha256$v=2,t=2b,r=4$tooshort$tooshort",
        # v=1 in the v2 template, and v=3: passlib raised on both.
        "$bcrypt-sha256$v=1,t=2b,r=4$y9oBZ09O8JN8BzEneZV4aO$wQRy9qZcuJOX5vMwsByLWRBk11zhck6",
        "$bcrypt-sha256$v=3,t=2b,r=4$y9oBZ09O8JN8BzEneZV4aO$wQRy9qZcuJOX5vMwsByLWRBk11zhck6",
        # Right shape, wrong bcrypt variant for v2 (only `2b` was ever written).
        "$bcrypt-sha256$v=2,t=2a,r=4$y9oBZ09O8JN8BzEneZV4aO$wQRy9qZcuJOX5vMwsByLWRBk11zhck6",
        # A too-short salt does not raise out of bcrypt's Rust extension, it
        # PANICS — `pyo3_runtime.PanicException` is a BaseException, so no
        # `except ValueError` catches it. The shape regex has to reject this
        # before `checkpw` ever sees it.
        "$2b$04$way-too-short",
        "$2b$04$" + "!" * 53,
        # crypt_blowfish's buggy 8-bit `$2x$` variant. bcrypt happily hashes it
        # as 2a; passlib refused it outright and so do we — nothing here ever
        # wrote one, so a row carrying it is corruption, not a credential.
        "$2x$04$0v0ttyuJTPtdZwHxLysDPOJjJ1Xz.Mpi6ky97ySg8ZRBSY5lgOl1i",
        # Cost outside bcrypt's 4..31 — a ValueError from the library, not a panic.
        "$2b$00$0v0ttyuJTPtdZwHxLysDPOJjJ1Xz.Mpi6ky97ySg8ZRBSY5lgOl1i",
        "$5$rounds=1000$sha-crypt-is-not-ours",
        "plaintext-password",
        "$2b$04$0v0ttyuJTPtdZwHxLysDPOJjJ1Xz.Mpi6ky97ySg8ZRBSY5lgOl1í",  # non-ascii
    ],
)
def test_a_malformed_or_foreign_hash_returns_false_rather_than_raising(hashed: str):
    """A 500 on the login path would be worse than a refusal, and an
    `hashed_password` column can hold anything a past migration put there."""
    assert pwd_context.verify("correctpw1", hashed) is False


def test_verify_tolerates_a_missing_hash():
    assert pwd_context.verify("correctpw1", None) is False  # type: ignore[arg-type]


def test_an_absurdly_long_secret_is_refused_on_write_but_still_costs_a_full_verify():
    """The ceiling is a write-side guard only, and that asymmetry is the point.

    `hash` refuses beyond `MAX_SECRET_BYTES` (passlib's own ceiling) — unreachable
    from any route, since every password-setting schema caps the field at 128
    characters, so reaching it is a programming error worth hearing about.

    `verify` must NOT refuse: `LoginRequest.password` has no maximum, so a fast
    rejection there would answer "does this account exist?" in microseconds where
    a wrong password costs ~200 ms of bcrypt — the enumeration oracle
    `dummy_verify` exists to close, handed straight back. An oversized secret
    therefore takes the normal path and returns a normal False.
    """
    huge = "a" * (MAX_SECRET_BYTES + 1)
    with pytest.raises(ValueError):
        pwd_context.hash(huge)
    assert pwd_context.verify(huge, dict(PASSLIB_V2)["correctpw1"]) is False


def test_verify_cost_does_not_depend_on_the_attempted_password_length():
    """The enumeration defence, from the hasher's side.

    Asserted as an order of magnitude, never a tight bound, so it cannot become a
    timing flake: an oversized attempt and an ordinary wrong one must both pay a
    full bcrypt, not one of them an early return.
    """
    hashed = dict(PASSLIB_V2)["correctpw1"]

    start = time.perf_counter()
    assert pwd_context.verify("wrong-password", hashed) is False
    ordinary = time.perf_counter() - start

    start = time.perf_counter()
    assert pwd_context.verify("a" * (MAX_SECRET_BYTES + 1), hashed) is False
    oversized = time.perf_counter() - start

    assert ordinary > 0
    assert 0.2 < oversized / ordinary < 5.0, (
        f"an oversized attempt ({oversized:.4f}s) diverged from an ordinary wrong "
        f"password ({ordinary:.4f}s) — a length-based early return is an "
        f"account-enumeration oracle"
    )


