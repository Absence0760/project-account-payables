def test_our_hash_is_the_v2_format_and_round_trips():
    hashed = pwd_context.hash("Correct-Horse-1234")
    assert hashed.startswith(f"$bcrypt-sha256$v=2,t=2b,r={DEFAULT_ROUNDS}$")
    # ['', 'bcrypt-sha256', 'v=2,t=2b,r=12', <22-char salt>, <31-char checksum>]
    fields = hashed.split("$")
    assert len(fields) == 5
    assert len(fields[3]) == 22
    assert len(fields[4]) == 31
    assert pwd_context.verify("Correct-Horse-1234", hashed) is True
    assert pwd_context.verify("Correct-Horse-1235", hashed) is False


def test_the_salt_lands_in_the_restricted_final_character_set():
    """bcrypt's 22-char salt carries four unused bits in its last character.

    Implementations disagree on how to hash a salt whose padding bits are set,
    so passlib forced them to zero — which restricts the final character to
    `.Oeu`. Our salts come from `bcrypt.gensalt`, which encodes exactly 16
    bytes and therefore has the property by construction; assert it, because a
    salt that lost it would produce digests other bcrypt builds disagree with.
    """
    for _ in range(25):
        salt = pwd_context.hash("Correct-Horse-1234").split("$")[3]
        assert salt[-1] in ".Oeu", salt


def test_two_hashes_of_the_same_password_differ():
    assert pwd_context.hash("Correct-Horse-1") != pwd_context.hash("Correct-Horse-1")


